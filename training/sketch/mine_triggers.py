"""mine_triggers.py: action cue words LEARNED from the training messages' trigger annotations (llm_train/*_msg/msg_*.jsonl), written to
docs/js/learned-cues.js. logic.js merges them into the legend's `action` cues at start-up, so the rules formalizer uses them, and
export_cues.mjs -> make_normalizer.py passes them to the VSS normalizer: one learned list for both readers (AGENTS.md, fair comparison).
Only the TRAINING messages are read; the test sets never are.

A trigger phrase becomes a cue of action A when: it occurs at least MIN_COUNT times as the trigger of a command, at least SHARE of those
occurrences are A, it is not already a cue (or value name) of another action, and it is not a stop word. Pronouns and names inside a
phrase trigger ("hook it up") are cut: the cue is the phrase up to the first pronoun/name ("hook"). Phrases that contain a value word of another legend question (below, row, huge, chain) are rejected: they mark the value, not the
action. Conflicts and rejected phrases are listed in llm_train/LEARNED_CUES.md. Run: python3 mine_triggers.py"""
import collections, glob, json, os, re, subprocess
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(HERE))
MIN_COUNT, SHARE = 2, 0.8
PRON = {"it", "them", "this", "that", "these", "those", "one", "ones", "him", "her", "everything", "all", "both", "the", "a", "an"}
STOP = {"is", "are", "be", "do", "does", "can", "could", "would", "please", "you", "i", "we", "me", "let", "lets", "let's", "want", "need",
        "should", "go", "get", "have", "has", "now", "then", "and", "so", "ok", "okay", "just", "also", "to", "on", "in", "of", "at", "for", "with"}


def cue_of(trigger, names):
    ws = re.findall(r"[A-Za-z][\w'-]*", trigger)
    out = []
    for w in ws:
        if w.lower() in PRON or w in names or w.lower() in {n.lower() for n in names}: break
        out.append(w.lower())
    while out and out[0] in STOP: out.pop(0)
    while out and out[-1] in STOP - {"up", "on", "off"}: out.pop()
    return " ".join(out)


def main():
    rows = [json.loads(l) for f in sorted(glob.glob(os.path.join(HERE, "llm_train", "*_msg", "msg_*.jsonl"))) for l in open(f) if l.strip()]
    cnt = collections.defaultdict(collections.Counter)
    for r in rows:
        names = set(r.get("names") or []) | {w["args"].get("name") for w in r["wires"] if w["args"].get("name")}
        for w in r["wires"]:
            if w.get("type") != "command" or not w.get("trigger"): continue
            c = cue_of(w["trigger"], names)
            if c: cnt[c][w["args"].get("action")] += 1
    existing = json.loads(subprocess.check_output(["node", "-e", """
      const K=require(process.argv[1]); const L=K.createSystem({learned:false}).engine.legend; const q=L.get('action'); const o={};
      for (const [v,cs] of Object.entries(q.values)) { o[v.toLowerCase()]=v; for (const c of cs) o[c.toLowerCase()]=v; } console.log(JSON.stringify(o));""",
                                                    os.path.join(REPO, "docs", "js", "logic.js")]))
    # words that answer OTHER legend questions (positions, colours, layouts, pairing, ...) or open a question are never action cues: an
    # annotator who marked "below" or "row" as the trigger marked the value, not the action
    cues = json.load(open(os.path.join(HERE, "legend_cues.json"))); base = json.load(open(os.path.join(HERE, "normalize_base.json")))
    value_words = {w for q, vs in cues.items() if q not in ("action",) for v, cs in vs.items() for c in [v] + list(cs) for w in c.lower().split()}
    value_words |= {w for r in base.get("rewrites", []) for alts in r["all"] for w in alts} | {"each", "every", "next", "its", "another", "chain", "chained"}
    learned, report = collections.defaultdict(list), []
    for c, ac in sorted(cnt.items(), key=lambda x: -sum(x[1].values())):
        n = sum(ac.values()); a, k = ac.most_common(1)[0]
        if c in STOP: why = "stop word"
        elif any(w in value_words for w in c.split()): why = "a value word of another legend question, not an action"
        elif n < MIN_COUNT: why = f"seen {n}x"
        elif k / n < SHARE: why = "ambiguous: " + ", ".join(f"{x} {y}" for x, y in ac.most_common())
        elif c in existing: why = "already a cue" + ("" if existing[c] == a else f" of {existing[c]} (conflict: data says {a})")
        else: learned[a].append(c); why = "LEARNED"
        report.append(f"| {c} | {n} | {', '.join(f'{x} {y}' for x, y in ac.most_common())} | {why} |")
    js = ("// learned-cues.js: GENERATED by training/sketch/mine_triggers.py from the training messages' trigger annotations. Do not edit.\n"
          "(function (root) { const C = " + json.dumps({"action": dict(sorted(learned.items()))}, sort_keys=True) + ";\n"
          "  if (typeof module !== 'undefined' && module.exports) module.exports = C; else root.SOP_LEARNED_CUES = C; })(this);\n")
    open(os.path.join(REPO, "docs", "js", "learned-cues.js"), "w").write(js)
    nl = sum(len(v) for v in learned.values())
    open(os.path.join(HERE, "llm_train", "LEARNED_CUES.md"), "w").write(
        f"# Action cues learned from the training triggers\n\n{len(rows)} training messages; {nl} cues learned (min count {MIN_COUNT}, share {SHARE}).\n\n"
        "| trigger (cut) | n | actions | decision |\n|---|---|---|---|\n" + "\n".join(report) + "\n")
    print(f"{len(rows)} messages, {len(cnt)} trigger phrases, {nl} learned cues:", {a: v for a, v in learned.items()})


if __name__ == "__main__":
    main()
