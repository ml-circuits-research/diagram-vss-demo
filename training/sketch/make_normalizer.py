"""make_normalizer.py: normalize.json = normalize_base.json (the grammar of the VSS front end: politeness, question openers, prepositional
phrases, numbers, names) + the legend's cue words (legend_cues.json, exported from docs/js/logic.js by export_cues.mjs, the same words the
rules formalizer uses), mapped to the sketch world's tokens. One word list for both readers: a cue added to the legend reaches the VSS
normalizer at the next build. Base entries win over legend cues; a single-word cue that is already a lexicon word of the world is left
alone (it is read as itself), and cues of questions the VSS world does not have (outline, ask, property, kind) are skipped."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)

TOKENS = {   # legend question -> value -> the world's token
    "action": {"create": "draw", "delete": "delete", "move": "move", "set": "color", "resize": "resize", "rename": "rename", "label": "label",
               "duplicate": "duplicate", "swap": "swap", "connect": "connect", "disconnect": "disconnect", "align": "align", "arrange": "arrange",
               "distribute": "distribute", "toFront": "bring", "toBack": "send", "undo": "undo", "redo": "redo", "forget": "forget"},
    "shape": {s: s for s in ["circle", "square", "rectangle", "triangle", "diamond", "ellipse", "hexagon", "star"]} | {"any": "shape"},
    "position": {"leftOf": "left_of", "rightOf": "right_of", "above": "above", "below": "below", "near": "next_to", "between": "between", "center": "center",
                 "top": "top", "bottom": "bottom", "left": "left_side", "right": "right_side", "topLeft": "top_left", "topRight": "top_right",
                 "bottomLeft": "bottom_left", "bottomRight": "bottom_right"},
    "axis": {"horizontal": "horizontally", "vertical": "vertically"}, "layout": {"row": "row", "column": "column", "grid": "grid", "circle": "ring"},
    "pairing": {"chain": "chain", "next": "next", "all": "each_other"}, "arrow": {"both": "two_way", "none": "plain"},
    "recency": {"newest": "newest", "oldest": "oldest"}, "comparison": {"bigger": "bigger", "smaller": "smaller"},
}
PLURAL = {"circle": "circles", "square": "squares", "rectangle": "rectangles", "triangle": "triangles", "diamond": "diamonds", "ellipse": "ellipses",
          "hexagon": "hexagons", "star": "stars", "shape": "shapes"}
SKIP_QUESTIONS = {"outline", "ask", "property", "kind", "quantifier"}
RESIZE = {"grow": "bigger_v", "enlarge": "bigger_v", "shrink": "smaller_v"}
# single words that are cues in the legend but too ambiguous for a word-for-word substitution ("first, draw ...", "connect both",
# "give it a label", "clear the rules"); the base table handles their phrases ("the first star", "two way")
AMBIGUOUS = {"first", "last", "latest", "earliest", "both", "none", "give", "clear", "reset", "new", "recent"}


def build(lexicon):
    base = json.load(open(os.path.join(HERE, "normalize_base.json")))
    cues = json.load(open(os.path.join(HERE, "legend_cues.json")))
    syn, mwe = dict(base["synonyms"]), [list(x) for x in base["mwe"]]
    have_mwe = {a for a, _ in mwe}
    structural = {w for a, _ in base["openers"] for w in a.split()[:1]} | set(base["lead_strip"])
    added = []
    for q, values in cues.items():
        if q in SKIP_QUESTIONS: continue
        for v, cs in values.items():
            if q in ("color", "size", "direction", "style"): tok = v
            elif q == "superlative": tok = v.lower()
            elif q == "notColor": tok = "not_" + v
            elif q in TOKENS and v in TOKENS[q]: tok = TOKENS[q][v]
            else: continue
            for c in ([v] if v == v.lower() else []) + list(cs):    # a camelCase value name (toFront) is not a word
                c = c.lower().strip()
                if not c or c == tok or c in AMBIGUOUS: continue
                if q == "action" and c in RESIZE: t = RESIZE[c]
                elif q == "shape" and (c.endswith("s") and c not in ("rhombus",)) : t = PLURAL.get(tok, tok)
                else: t = tok
                if " " in c:
                    if c not in have_mwe: mwe.append([c, t]); have_mwe.add(c); added.append((c, t))
                elif c not in syn and c not in lexicon and c not in structural:
                    syn[c] = t; added.append((c, t))
    out = dict(base); out["synonyms"] = syn; out["mwe"] = mwe
    out["about"] = base["about"] + " Generated by make_normalizer.py: the synonyms and multi-word expressions include the legend's cue words (legend_cues.json)."
    json.dump(out, open(os.path.join(HERE, "normalize.json"), "w"), indent=1)
    return added


if __name__ == "__main__":
    from generate import LEXICON
    added = build(LEXICON)
    print(f"normalize.json written: {len(added)} legend cues added to the base table")
    print(", ".join(f"{a}->{b}" for a, b in added[:80]))
